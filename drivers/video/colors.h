#ifndef COLORS_H
#define COLORS_H

#include <stdint.h>

typedef uint32_t Color;

#define BLACK  (Color)0x00000000
#define RED    (Color)0x00FF0000
#define ORANGE (Color)0x00FF6600
#define YELLOW (Color)0x00FFFF00
#define GREEN  (Color)0x0000FF00
#define BLUE   (Color)0x000000FF
#define PURPLE (Color)0x009900CC
#define PINK   (Color)0x00FF0099
#define WHITE  (Color)0x00FFFFFF
#endif